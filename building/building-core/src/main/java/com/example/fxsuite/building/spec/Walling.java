package com.example.fxsuite.building.spec;

/**
 * What a building's walls are filled in with between its structure, as a specification says it: each civilization's
 * implementation making it its own way.
 */
public enum Walling {
    /** Brick, laid in courses. */
    BRICK,
    /** Panels of concrete cast elsewhere and set up whole. */
    PRECAST,
    /** Concrete cast where it stands. */
    CONCRETE,
    /** Dressed stone, laid in courses. */
    STONE
}
